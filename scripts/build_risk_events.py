import json
import os
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.metrics import average_precision_score, f1_score, precision_score, recall_score
from sklearn.model_selection import StratifiedKFold
from scripts.db import get_connection

METRICS_PATH = os.path.join("data", "model_metrics.json")
THRESHOLD = 66


def compute_rule_score(df: pd.DataFrame) -> np.ndarray:
    """Deterministic 0-100 risk score from transaction/velocity signals."""
    amt_high = (pd.to_numeric(df["amount_inr"], errors="coerce").fillna(0) >= 25000).astype(float) * 35.0
    failed_or_pending = df["status"].isin(["FAILED", "PENDING"]).astype(float) * 25.0
    high_latency = (pd.to_numeric(df["latency_ms"], errors="coerce").fillna(0) >= 1200).astype(float) * 20.0

    ts = pd.to_datetime(df["txn_timestamp"], errors="coerce")
    hour = ts.dt.hour.fillna(12)
    late_night = hour.between(0, 4).astype(float) * 20.0

    score = amt_high + failed_or_pending + high_latency + late_night
    return np.clip(score, 0.0, 100.0)


def compute_oof_if_score(df: pd.DataFrame, n_splits: int = 5, random_state: int = 42) -> np.ndarray:
    """
    Computes out-of-fold anomaly scores (0-100) using StratifiedKFold so each
    transaction's IsolationForest score is generated by a model fit without seeing
    that transaction's fold.
    """
    ts = pd.to_datetime(df["txn_timestamp"], errors="coerce")
    features = pd.DataFrame(
        {
            "amount_inr": pd.to_numeric(df["amount_inr"], errors="coerce").fillna(0.0),
            "latency_ms": pd.to_numeric(df["latency_ms"], errors="coerce").fillna(0.0),
            "txn_hour": ts.dt.hour.fillna(12).astype(float),
            "is_failed": (df["status"] == "FAILED").astype(float),
            "is_pending": (df["status"] == "PENDING").astype(float),
        },
        index=df.index,
    )

    y = pd.to_numeric(df["is_fraud"], errors="coerce").fillna(0).astype(int).to_numpy()
    oof_raw = np.zeros(len(df), dtype=float)

    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    for _, val_idx in skf.split(features, y):
        train_mask = np.ones(len(df), dtype=bool)
        train_mask[val_idx] = False

        iso = IsolationForest(
            n_estimators=150,
            contamination=0.03,
            random_state=random_state,
        )
        iso.fit(features.loc[train_mask])
        # decision_function: lower/more negative => more anomalous
        oof_raw[val_idx] = -iso.decision_function(features.iloc[val_idx])

    min_v, max_v = float(oof_raw.min()), float(oof_raw.max())
    if max_v > min_v:
        oof_score = 100.0 * (oof_raw - min_v) / (max_v - min_v)
    else:
        oof_score = np.zeros_like(oof_raw)
    return np.clip(oof_score, 0.0, 100.0)


def evaluate_variant(name: str, y_true: np.ndarray, scores: np.ndarray, threshold: int = THRESHOLD) -> dict:
    preds = (scores >= threshold).astype(int)
    return {
        "Model Variant": name,
        "Threshold": threshold,
        "Precision": round(float(precision_score(y_true, preds, zero_division=0)), 4),
        "Recall": round(float(recall_score(y_true, preds, zero_division=0)), 4),
        "F1 Score": round(float(f1_score(y_true, preds, zero_division=0)), 4),
        "PR-AUC": round(float(average_precision_score(y_true, scores)), 4),
        "Flagged Txns": int(preds.sum()),
    }


def main():
    conn, backend = get_connection()
    try:
        df = pd.read_sql(
            """
            SELECT txn_id, user_id, txn_timestamp, amount_inr, status, latency_ms, is_fraud
            FROM transactions
            ORDER BY txn_id
            """,
            conn,
        )
    finally:
        conn.close()

    y_true = pd.to_numeric(df["is_fraud"], errors="coerce").fillna(0).astype(int).to_numpy()
    rule_score = compute_rule_score(df)
    oof_ml_score = compute_oof_if_score(df, n_splits=5, random_state=42)

    hybrid_50_score = 0.50 * rule_score + 0.50 * oof_ml_score
    hybrid_75_score = 0.75 * rule_score + 0.25 * oof_ml_score

    models = [
        evaluate_variant("SQL Rules Only", y_true, rule_score, THRESHOLD),
        evaluate_variant("Isolation Forest Only (OOF)", y_true, oof_ml_score, THRESHOLD),
        evaluate_variant("Hybrid (50% SQL / 50% ML-OOF)", y_true, hybrid_50_score, THRESHOLD),
        evaluate_variant("Hybrid (75% SQL / 25% ML-OOF)", y_true, hybrid_75_score, THRESHOLD),
    ]

    os.makedirs(os.path.dirname(METRICS_PATH), exist_ok=True)
    payload = {
        "validation_method": "5-fold stratified out-of-fold",
        "n_splits": 5,
        "threshold": THRESHOLD,
        "models": models,
    }
    with open(METRICS_PATH, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    print(f"Wrote {METRICS_PATH} using {payload['validation_method']}.")


if __name__ == "__main__":
    main()